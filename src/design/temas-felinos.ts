import type { Projeto } from "../tipos";
import { corPixel } from "../temas/catalogo.ts";

export interface TemaFelino {
  id: string;
  nome: string;
  desenho: string[];
}

function espalhar(texto: string) {
  let hash = 0x811c9dc5;
  for (const letra of texto) {
    hash ^= letra.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 0x01000193);
  }
  hash = Math.imul(hash ^ (hash >>> 16), 0x85ebca6b);
  hash = Math.imul(hash ^ (hash >>> 13), 0xc2b2ae35);
  return (hash ^ (hash >>> 16)) >>> 0;
}

export function temasDosProjetos(projetos: Projeto[]) {
  const usos = new Array<number>(TEMAS.length).fill(0);
  const temas = new Map<string, TemaFelino>();
  [...projetos]
    .sort(
      (a, b) =>
        a.criadoEm.localeCompare(b.criadoEm) ||
        a.id.localeCompare(b.id, "pt-BR", { numeric: true }),
    )
    .forEach((projeto, posicao) => {
      const rodada = Math.floor(posicao / TEMAS.length);
      let indice = espalhar(projeto.id) % TEMAS.length;
      while (usos[indice] > rodada) indice = (indice + 1) % TEMAS.length;
      usos[indice]++;
      temas.set(projeto.id, TEMAS[indice]);
    });
  return temas;
}

export function camadasDoTema(tema: TemaFelino) {
  const caminhos = new Map<string, string>();
  tema.desenho.forEach((linha, y) => {
    for (const { 0: corrida, index: x } of linha.matchAll(/([^.])\1*/g)) {
      const cor = corrida[0];
      const d = `M${x} ${y}h${corrida.length}v1h-${corrida.length}z`;
      caminhos.set(cor, (caminhos.get(cor) ?? "") + d);
    }
  });
  return [...caminhos].map(([cor, d]) => ({ cor: corPixel(PALETA[cor]), d }));
}

